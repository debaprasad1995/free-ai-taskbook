/* Transparent local keyword matching, no paid AI API or user prompt collection. */
(()=>{document.addEventListener('DOMContentLoaded',()=>{
 const form=document.getElementById('tool-finder-form');
 const result=document.getElementById('tool-finder-results');
 if(!form||!result)return;
 const goal=document.getElementById('tool-finder-goal');
 const synonyms={brd:['business','requirements','document','analysis'],prd:['product','requirements','document'],sow:['scope','work','document'],wireframe:['design','prototype','ui'],figma:['design','ui','ux'],sql:['database','data','query'],dashboard:['analytics','data','report'],chatbot:['chat','ai','coding'],website:['web','builder','coding'],video:['video','editing','generation'],api:['integration','developer','api'],resume:['writing','career','job']};
 const stop=new Set(['the','and','for','with','from','want','need','help','make','create','free','tool','tools','using','please','can','you','how','this','that']);
 function tokens(text){return [...new Set(String(text).toLowerCase().match(/[a-z0-9]+/g)||[])].filter(x=>x.length>2&&!stop.has(x));}
 function render(rows,query){
  result.replaceChildren();const terms=tokens(query),expanded=[...new Set([...terms,...terms.flatMap(x=>synonyms[x]||[])])];
  const ranked=rows.filter(x=>x.type==='AI tool'||x.type==='API').map(x=>{
    const name=String(x.name||'').toLowerCase(),hay=String(x.search||'').toLowerCase();
    let points=0;
    for(const t of expanded){if(name.includes(t))points+=5;if(hay.includes(t))points+=2;}
    if(x.pricing==='free'||x.pricing==='local-open-source')points+=2;
    else if(x.pricing==='free-tier')points+=1;
    return {...x,points};
  }).filter(x=>x.points>0).sort((a,b)=>b.points-a.points||a.name.localeCompare(b.name)).slice(0,5);
  const h=document.createElement('h3');h.textContent=ranked.length?'Suggested tools for your task':'No close match found';result.append(h);
  if(!ranked.length){const p=document.createElement('p');p.textContent='Try a more specific task, or browse the full directory below.';result.append(p);return;}
  const list=document.createElement('div');list.className='smart-finder-matches';result.append(list);
  for(const x of ranked){
   const box=document.createElement('article');box.className='smart-match';
   const label=document.createElement('strong');label.textContent=x.name;
   const meta=document.createElement('span');meta.textContent=x.pricing+' · '+x.type;
   const desc=document.createElement('p');desc.textContent=x.description||'See details and limitations.';
   const link=document.createElement('a');link.textContent='View details ↗';
   try{const u=new URL(x.url,location.origin);link.href=u.protocol==='https:'?u.href:'/search/';}catch{link.href='/search/';}
   if(!link.href.startsWith(location.origin)){link.target='_blank';link.rel='noopener noreferrer';}
   box.append(label,meta,desc,link);list.append(box);
  }
  const note=document.createElement('p');note.className='smart-finder-note';note.textContent='Ranked by keyword overlap and free-access classification; not generated by a language model. Verify current limits with each provider.';result.append(note);
 }
 form.addEventListener('submit',async e=>{
  e.preventDefault();result.textContent='Finding matching tools…';
  try{const r=await fetch('/search-index.json?v=__SEARCH_INDEX_VERSION__',{cache:'no-store'});if(!r.ok)throw Error('search index');render(await r.json(),goal.value);}catch{result.textContent='Suggestions are unavailable. Please use the directory search below.';}
 });
});})();
